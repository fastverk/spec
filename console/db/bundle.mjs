#!/usr/bin/env node
/**
 * Emit every migration as ONE script, for pasting into a SQL console.
 *
 *   node db/bundle.mjs > db/bootstrap.sql
 *
 * Why this exists: applying the migrations needs a Postgres connection, and the
 * obvious way to get one — paste a live credential somewhere it will be logged —
 * is a bad trade for a one-off. Neon's own SQL editor already has a connection,
 * authenticated as the owner, in a browser tab. This is the same DDL in a form
 * that can go there.
 *
 * ⛔ It writes the ledger rows too, with each file's real sha256. Without them a
 * later `node db/migrate.mjs` would try to re-apply everything and fail on
 * objects that already exist; with them it says "nothing to apply". The two
 * paths must not disagree about what has been applied.
 *
 * ⚠ Generated. Re-run after changing any migration — `db/check-bundle.mjs`
 * fails CI if this file and the migrations have drifted.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const out = [];
out.push("-- GENERATED by db/bundle.mjs — do not edit. Re-run the generator.");
out.push("--");
out.push("-- Every migration, in order, plus the ledger rows that record them as");
out.push("-- applied. Paste into the Neon SQL editor as the OWNER role.");
out.push("--");
out.push("-- Safe to run once. Running it twice fails on objects that already exist,");
out.push("-- which is the honest outcome — check the ledger rather than re-running:");
out.push("--     SELECT filename, applied_at FROM spec.schema_migration ORDER BY filename;");
out.push("");
out.push("BEGIN;");
out.push("");
out.push("CREATE SCHEMA IF NOT EXISTS spec;");
out.push("CREATE TABLE IF NOT EXISTS spec.schema_migration (");
out.push("    filename   text PRIMARY KEY,");
out.push("    sha256     text NOT NULL,");
out.push("    applied_at timestamptz NOT NULL DEFAULT clock_timestamp()");
out.push(");");
out.push("");

for (const f of files) {
  const body = readFileSync(join(dir, f), "utf8");
  const sha = createHash("sha256").update(body).digest("hex");
  out.push(`-- ${"─".repeat(72)}`);
  out.push(`-- ${f}`);
  out.push(`-- ${"─".repeat(72)}`);
  out.push(body.trimEnd());
  out.push("");
  out.push(
    `INSERT INTO spec.schema_migration (filename, sha256) VALUES ('${f}', '${sha}');`,
  );
  out.push("");
}

out.push("COMMIT;");
out.push("");
out.push("-- What you should see afterwards:");
out.push("--   SELECT tablename, tableowner FROM pg_tables WHERE schemaname = 'spec';");
out.push("--     proposal_log    | spec_owner");
out.push("--     evaluation_log  | spec_owner");
out.push("--");
out.push("-- Then give the app role a password — it has none, so it cannot connect yet:");
out.push("--   ALTER ROLE spec_app WITH PASSWORD '<generate one>';");

process.stdout.write(out.join("\n") + "\n");
