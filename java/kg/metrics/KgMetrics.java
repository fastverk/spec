    private static void renderLintHeartbeat(Dataset dsAuthored, Path kgRoot, StringBuilder out) throws IOException {
        out.append("## Lint heartbeat\n\n");
        out.append("> Live count of every `kg_lint` check. A check enters at `warning`;\n");
        out.append("> when the count reaches zero it gets promoted to `error` and pinned to\n");
        out.append("> `//ci:pr_gates` (the ratchet — see `kg/lint/`).\n>\n");
        out.append("> Counts here match `kg_lint run`: queries see authored + reasoner-inferred\n");
        out.append("> triples (so the orphan-diagnostic count reflects rule-derived `:emits` links).\n\n");
        out.append("| Check | Severity | Violations |\n|---|---|---|\n");
        // Each check uses its declared dataset (authored or inferred-aware)
        // matching `kg_lint run`. Counts are uncapped totals so the
        // dashboard reflects real progress even when row displays cap at 100.
        Dataset dsInferred = Loader.loadDatasetWithInferred(kgRoot);
        List<LintCheck> checks = KgLint.loadChecks(kgRoot.resolve("lint"));
        for (LintCheck c : checks) {
            Dataset ds = c.inferred ? dsInferred : dsAuthored;
            int n = c.runWithTotal(ds).total;
            String row = String.format(
                "| `%s` | %s | %s |\n",
                c.name,
                c.severity.name().toLowerCase(),
                n == 0 ? "✓ 0" : (c.severity == LintCheck.Severity.ERROR ? "✗ " + n : "! " + n));
            out.append(row);
        }
        long warnTotal = 0, errTotal = 0;
        List<String> ready = new ArrayList<>();
        for (LintCheck c : checks) {
            Dataset checkDs = c.inferred ? dsInferred : dsAuthored;
            int total = c.runWithTotal(checkDs).total;
            if (c.severity == LintCheck.Severity.WARNING) warnTotal += total;
            if (c.severity == LintCheck.Severity.ERROR)   errTotal  += total;
            if (c.severity == LintCheck.Severity.WARNING && total == 0) ready.add(c.name);
        }
        out.append('\n');
        out.append("**Totals:** ").append(warnTotal).append(" warning row(s), ")
           .append(errTotal).append(" error row(s).\n\n");
        out.append("Promotion candidates (warning checks at zero violations): ");
        out.append(ready.isEmpty() ? "_(none yet)_" : String.join(", ", ready)).append("\n");
    }

