    private static void renderInferred(Path kgRoot, StringBuilder out) {
        out.append("## Inferred triples\n\n");
        out.append("> Output of `kg_reasoner` — derivations from the authored corpus\n");
        out.append("> (OWL-MICRO closure today; rule-based and LLM-gated layers in v2.1+).\n");
        out.append("> Each derived triple carries a `rfc:inferredBy` provenance marker.\n\n");

        Path inferredFile = kgRoot.resolve("inferred").resolve("aion-inferred.ttl");
        if (!Files.isRegularFile(inferredFile)) {
            out.append("_(reasoner has not been run; run `bazel run //kg/java/reasoner:kg_reasoner`)_\n\n");
            return;
        }
        Dataset inferred = ds_loadInferred(kgRoot);
        out.append("| Metric | Count |\n|---|---|\n");
        out.append(row("Inferred triples",
            count(inferred,
                "PREFIX rfco: <" + RFC_PREFIX + "> "
                + "SELECT (COUNT(DISTINCT ?r) AS ?n) WHERE { ?r rfco:inferredBy ?tag }")));
        out.append(row("New transitive `dependsOn` edges",
            count(inferred,
                "PREFIX rfco: <" + RFC_PREFIX + "> PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>\n"
                + "SELECT (COUNT(DISTINCT ?r) AS ?n) WHERE {\n"
                + "  ?r rfco:inferredBy ?tag ; rdf:predicate rfco:dependsOn .\n"
                + "}")));
        out.append(row("New `extendedBy` edges (from `extends` inverse)",
            count(inferred,
                "PREFIX rfco: <" + RFC_PREFIX + "> PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>\n"
                + "SELECT (COUNT(DISTINCT ?r) AS ?n) WHERE {\n"
                + "  ?r rfco:inferredBy ?tag ; rdf:predicate rfco:extendedBy .\n"
                + "}")));
        out.append('\n');
    }

    /** Load just the inferred file as a standalone Dataset for query. */
    private static Dataset ds_loadInferred(Path kgRoot) {
        org.apache.jena.rdf.model.Model m = org.apache.jena.rdf.model.ModelFactory.createDefaultModel();
        Path f = kgRoot.resolve("inferred").resolve("aion-inferred.ttl");
        if (Files.isRegularFile(f)) {
            org.apache.jena.riot.RDFDataMgr.read(m, f.toUri().toString());
        }
        return org.apache.jena.query.DatasetFactory.create(m);
    }

