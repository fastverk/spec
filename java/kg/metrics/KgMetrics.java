    private static int count(Dataset ds, String sparql) {
        try (QueryExecution exec = QueryExecutionFactory.create(QueryFactory.create(sparql), ds)) {
            ResultSet rs = exec.execSelect();
            if (!rs.hasNext()) return 0;
            QuerySolution s = rs.next();
            // Single-column SELECT — read whichever variable exists.
            String v = rs.getResultVars().get(0);
            return s.getLiteral(v).getInt();
        }
    }

    private static String row(String label, Object value) {
        return "| " + label + " | " + value + " |\n";
    }

    private static String pct(int part, int total) {
        if (total == 0) return part + " / 0 (n/a)";
        double p = 100.0 * part / total;
        return String.format("%d / %d (%.1f%%)", part, total, p);
    }

    private static Path resolveDocsRoot() {
        String testSrcDir = System.getenv("TEST_SRCDIR");
        String testWorkspace = System.getenv("TEST_WORKSPACE");
        if (testSrcDir != null && testWorkspace != null) {
            Path p = Paths.get(testSrcDir, testWorkspace, "narrative");
            if (Files.isDirectory(p)) return p;
        }
        String workspace = System.getenv("BUILD_WORKSPACE_DIRECTORY");
        if (workspace != null) {
            Path p = Paths.get(workspace, "narrative");
            if (Files.isDirectory(p)) return p;
        }
        Path cwd = Paths.get("narrative");
        if (Files.isDirectory(cwd)) return cwd;
        throw new IllegalStateException("could not locate narrative/ directory");
    }
