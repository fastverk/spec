    // -----------------------------------------------------------------------
    // Coverage — Tier-2 → Tier-3 migration indicators
    // -----------------------------------------------------------------------

    private static void renderCoverage(Dataset ds, StringBuilder out) {
        out.append("## Tier-2 → Tier-3 coverage\n\n");
        out.append("> Each metric below tracks how much of the corpus's normative content has\n");
        out.append("> moved from free-text into structured, queryable form. Higher is better.\n\n");
        out.append("| Metric | Value |\n|---|---|\n");

        int totalTerms = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + "> SELECT (COUNT(DISTINCT ?t) AS ?n) WHERE { ?t a rfc:Term }");
        int citedTerms = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + ">\n" +
            "PREFIX claim: <https://aion.savvi.io/ontology/claims#>\n" +
            "SELECT (COUNT(DISTINCT ?t) AS ?n) WHERE {\n" +
            "  ?t a rfc:Term ; rfc:name ?name .\n" +
            "  ?c a claim:Claim .\n" +
            "  FILTER EXISTS { ?c ?p ?o . FILTER(isLiteral(?o) && CONTAINS(LCASE(STR(?o)), LCASE(?name))) }\n" +
            "}");
        out.append(row("Terms cited in ≥1 claim", pct(citedTerms, totalTerms)));

        int totalDiag = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + "> SELECT (COUNT(DISTINCT ?d) AS ?n) WHERE { ?d a rfc:Diagnostic }");
        // Diagnostics aren't yet linked to rules; once :emits lands this becomes meaningful.
        // For now we report 0 to give the metric a "starting line" in the timeseries.
        int linkedDiag = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + ">\n" +
            "SELECT (COUNT(DISTINCT ?d) AS ?n) WHERE {\n" +
            "  ?d a rfc:Diagnostic .\n" +
            "  FILTER EXISTS { ?rule rfc:emits ?d }\n" +
            "}");
        out.append(row("Diagnostics linked via `:emits`", pct(linkedDiag, totalDiag)
            + " _(populate via `kg_edit scaffold-rule --emits …` or v2.1 reasoner rules)_"));

        // Cross-RFC reference health — fraction of `:references` that resolve.
        int totalRefs = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + "> SELECT (COUNT(*) AS ?n) WHERE { ?a rfc:references ?b }");
        int resolvingRefs = count(ds,
            "PREFIX rfc: <" + RFC_PREFIX + "> SELECT (COUNT(*) AS ?n) WHERE { ?a rfc:references ?b . ?b a rfc:Document }");
        out.append(row("`:references` resolving to an RFC Document", pct(resolvingRefs, totalRefs)));

        out.append('\n');
    }

